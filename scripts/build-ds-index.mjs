#!/usr/bin/env node
/**
 * Build design-system/index-data.js from index.json + each template.json.
 * Auto-detects which design-system/<slug>.html pages exist and marks them available.
 * Re-run after adding any new <slug>.html page.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const tplDir = path.join(root, 'templates');
const dsDir = path.join(root, 'design-system');

const idx = JSON.parse(fs.readFileSync(path.join(root, 'index.json'), 'utf8'));
const bySlug = Object.fromEntries(idx.templates.map((t) => [t.slug, t]));

const data = fs
  .readdirSync(tplDir)
  .filter((s) => fs.existsSync(path.join(tplDir, s, 'template.json')))
  .map((s) => {
    const j = JSON.parse(fs.readFileSync(path.join(tplDir, s, 'template.json'), 'utf8'));
    const meta = bySlug[s] || {};
    const palette = j.palette
      ? Object.entries(j.palette)
          .filter(([k]) => k !== 'description')
          .map(([k, v]) => ({ k, v }))
      : [];
    return {
      slug: j.slug,
      name: j.name,
      tagline: j.tagline || meta.tagline || '',
      scheme: j.scheme || meta.scheme || 'light',
      mood: (j.mood || meta.mood || []).slice(0, 3),
      display: (j.typography && j.typography.display) || null,
      palette,
      available: fs.existsSync(path.join(dsDir, `${s}.html`)),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const out = `/* AUTO-GENERATED by scripts/build-ds-index.mjs — do not edit by hand */\nwindow.DECK_INDEX = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(dsDir, 'index-data.js'), out);
console.log(`wrote design-system/index-data.js (${data.length} templates, ${data.filter((d) => d.available).length} available: ${data.filter((d) => d.available).map((d) => d.slug).join(', ')})`);
